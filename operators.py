# operators perform actions on values/variables
# Arithmetic: +, -, *, /, //, %, **
# Comparison: ==, !=, >, <, >=, <=
# logical: and, or, not
# Assignment: =, +=, -=, /=

a = 10
b = 3

print(a + b)    # 13
print(a // b)   # 3 floor division
print(a % b)    # 1 reminder
print(a ** b)   # 1000 power
print(a > b > 0) # True
