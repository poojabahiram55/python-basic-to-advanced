# A variable is a name that store a value in memory
# Python is dynamically typed - you don't declare the type, it's inferred automatically
# Main basic types: int, float, str, bool

names = 'Aman'
age =  29
height = 5.9
is_active = True

print(type(names))      # <class 'str'>
print(type(age))        # <class 'int'>
print(type(height))     # <class 'float'>
print(type(is_active))  # <class 'bool'>

